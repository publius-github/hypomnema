/// Whether `bytes` at vault-relative `relative` is still what
/// `Vault::open` seeded a config file with - the starter rules or the
/// commented sample, nothing anyone wrote. Sync lets such a file give
/// way to the other device's version instead of keeping it as a
/// conflicted copy.
pub fn is_untouched_sample(relative: &str, bytes: &[u8]) -> bool {
    let Some(file) = relative
        .strip_prefix(WORK_DIR)
        .and_then(|rest| rest.strip_prefix("/config/"))
    else {
        return false;
    };
    CONFIG_STARTERS
        .iter()
        .chain(CONFIG_SAMPLES)
        .any(|(name, sample)| *name == file && sample.as_bytes() == bytes)
}

/// All working files live under this hidden folder in the vault root,
/// like the .git of a repository: the user's own content (journal/,
/// notes) stays at the top level, the app's machinery does not.
pub const WORK_DIR: &str = ".hypomnema";

pub fn work_dir(root: &Path) -> PathBuf {
    root.join(WORK_DIR)
}

/// User configs: recurring.yml, scheduled.yml, birthdays.yml and the
/// other content-bearing files (plus pack subfolders and templates/).
pub fn config_dir(root: &Path) -> PathBuf {
    work_dir(root).join("config")
}

/// App settings (app.yml) - deliberately a different folder from the
/// user configs above.
pub fn settings_file(root: &Path) -> PathBuf {
    work_dir(root).join("settings").join("app.yml")
}

/// A synced slice of the settings (`config::SyncedPart`: the color
/// scheme in colors.yml, the rules every device must share in
/// shared.yml): user configs, so they sync, unlike app.yml.
pub fn synced_file(root: &Path, part: SyncedPart) -> PathBuf {
    config_dir(root).join(part.file())
}

pub fn db_path(root: &Path) -> PathBuf {
    work_dir(root).join("app.db")
}

/// The bulk-editable Markdown task mirror.
pub fn tasks_dir(root: &Path) -> PathBuf {
    work_dir(root).join("tasks")
}

/// App-written text state (never the human-editing surface): the full
/// database snapshot (state_export.rs) and the mirror merge base.
pub fn state_dir(root: &Path) -> PathBuf {
    work_dir(root).join("state")
}

/// Copies of the mirror files as the app last exported them - the merge
/// base of the mirror import. Outside tasks_dir so the watcher never
/// sees them, and file-sync friendly: a stale or concurrently edited
/// mirror file merges against this instead of overwriting the database.
pub fn mirror_base_dir(root: &Path) -> PathBuf {
    state_dir(root).join("mirror-base")
}

/// One-time move of the pre-0.32 flat layout (app.db, config/, backups/,
/// tasks/ in the vault root) into .hypomnema/, and of app.yml out of the
/// user configs into settings/. Every step is skipped when the source is
/// gone or the target already exists, so a half-done move just resumes.
fn migrate_layout(root: &Path) -> Result<()> {
    let work = work_dir(root);
    let move_item = |from: PathBuf, to: PathBuf| {
        if from.exists() && !to.exists() {
            if let Some(parent) = to.parent() {
                let _ = fs::create_dir_all(parent);
            }
            let _ = fs::rename(&from, &to);
        }
    };
    for name in ["app.db", "app.db-wal", "app.db-shm"] {
        move_item(root.join(name), work.join(name));
    }
    move_item(root.join("config"), work.join("config"));
    move_item(root.join("backups"), work.join("backups"));
    move_item(root.join("tasks"), work.join("tasks"));
    // settings split away from the user configs
    move_item(work.join("config").join("app.yml"), settings_file(root));
    Ok(())
}

pub struct Vault {
    pub root: PathBuf,
    pub config: AppConfig,
    pub conn: Connection,
    /// Set when app.yml could not be parsed and defaults are active;
    /// surfaced through the engine outcome as a config error banner.
    pub config_error: Option<String>,
    /// True when this open created the database: a vault nobody has
    /// used yet, on this device or (through a synced snapshot) another.
    /// The opener seeds the starter lists into such a vault.
    pub fresh: bool,
}

impl Vault {
    /// Opens (or initializes) the vault: folder layout, app.yml with
    /// defaults, SQLite DB with migrations, and the settings mirror.
    pub fn open(root: &Path) -> Result<Self> {
        if !root.is_dir() {
            return Err(Error::State(format!(
                "vault folder does not exist: {}",
                root.display()
            )));
        }

        migrate_layout(root)?;
        let config_dir = config_dir(root);
        fs::create_dir_all(&config_dir).at(&config_dir)?;
        fs::create_dir_all(config_dir.join("templates")).at(&config_dir.join("templates"))?;
        fs::create_dir_all(root.join("journal")).at(&root.join("journal"))?;

        // no database and no snapshot to rebuild one from: nobody has
        // used this vault anywhere, so it gets the starter content; a
        // vault in use only gets a commented sample for a file it lacks
        let fresh = !db_path(root).exists() && !state_dir(root).join("tasks.jsonl").exists();
        let seeds = if fresh {
            CONFIG_STARTERS
        } else {
            CONFIG_SAMPLES
        };
        for (file, sample) in seeds {
            let path = config_dir.join(file);
            if !path.exists() {
                fs::write(&path, sample).at(&path)?;
            }
        }

        let (config, config_error) = AppConfig::load_or_default(&settings_file(root), &config_dir);

        let conn = match open_db(root, &config) {
            Ok(conn) => conn,
            // A database SQLite cannot read is a cache like any other
            // when the snapshot is there to rebuild it from: set it
            // aside (never deleted - it may still be worth a look) and
            // open a fresh one. Without a snapshot it is the only copy,
            // and the open fails instead.
            Err(e) if is_unreadable_db(&e) && state_dir(root).join("tasks.jsonl").exists() => {
                let aside = set_aside_unreadable_db(root, Local::now())?;
                crate::applog::warn(format!(
                    "app.db could not be read ({e}); moved to {} and rebuilt from the snapshot",
                    aside.display()
                ));
                open_db(root, &config)?
            }
            Err(e) => return Err(e),
        };
        // An empty database is rebuilt from the state snapshot BEFORE
        // anything can export it over the snapshot: a vault without its
        // .db (fresh sync copy, deleted cache), but just as much one whose
        // restore failed or was cut short - the file exists then, empty,
        // and must not pass for a vault with nothing in it. A broken
        // snapshot aborts the open, and the next open tries again.
        if crate::state_export::db_is_empty(&conn)? {
            crate::state_export::restore(&conn, &state_dir(root))?;
        }
        db::mirror_settings(&conn, &config)?;
        // Daily snapshot before the first engine pass of the day, so it
        // captures yesterday's end state. Best effort: a failed backup
        // must not make the vault unopenable.
        if let Err(e) =
            crate::backup::backup_db_daily(&conn, root, config.backup_keep, Local::now())
        {
            crate::applog::warn(format!("daily database backup failed: {e}"));
        }

        Ok(Self {
            root: root.to_path_buf(),
            config,
            conn,
            config_error,
            fresh,
        })
    }

    pub fn save_config(&mut self, config: AppConfig) -> Result<()> {
        let config = config.sanitized();
        config.save(&settings_file(&self.root))?;
        // only a real change writes a synced file: rewriting it on every
        // setting would push this device's copy over a newer one another
        // device synced in meanwhile
        for part in SyncedPart::ALL {
            if config.part_mapping(part)? != self.config.part_mapping(part)? {
                // best effort, like every config backup: a failed copy
                // must not block the change
                let _ = crate::backup::backup_config_file(
                    &config_dir(&self.root),
                    part.file(),
                    config.backup_keep,
                    Local::now(),
                );
                config.save_part(part, &synced_file(&self.root, part))?;
            }
        }
        db::mirror_settings(&self.conn, &config)?;
        self.config = config;
        self.config_error = None;
        Ok(())
    }

    pub fn config_dir(&self) -> PathBuf {
        config_dir(&self.root)
    }

    /// Re-reads app.yml and the synced files (e.g. after an external
    /// edit or a sync pass) and refreshes the settings mirror. The files
    /// are the source of truth (req. 23).
    pub fn reload_config(&mut self) -> Result<()> {
        let path = settings_file(&self.root);
        if !path.exists() {
            return Ok(());
        }
        match AppConfig::read(&path, &config_dir(&self.root)) {
            Ok((mut config, errors)) => {
                // a synced file broken mid-session keeps its fields as
                // they were
                let mut messages = Vec::new();
                for (part, e) in errors {
                    config = config.with_part(part, &self.config.part_mapping(part)?)?;
                    messages.push(format!(
                        "invalid {}, previous values stay active: {e}",
                        part.file()
                    ));
                }
                db::mirror_settings(&self.conn, &config)?;
                self.config = config;
                self.config_error = messages.into_iter().reduce(|a, b| format!("{a}; {b}"));
            }
            // A broken file mid-session keeps the last valid settings
            // active (req. 19) and only raises the banner.
            Err(e) => {
                self.config_error = Some(format!(
                    "invalid app.yml, previous settings stay active: {e}"
                ));
            }
        }
        Ok(())
    }
}

/// Opens app.db and brings its schema up to date, snapshotting an older
/// schema first.
fn open_db(root: &Path, config: &AppConfig) -> Result<Connection> {
    let conn = db::open(&db_path(root))?;
    if let Some(from) = db::pending_upgrade_from(&conn)? {
        // Not best effort, unlike the daily snapshot: a schema
        // upgrade is not undoable, so without a copy it does not run.
        crate::backup::backup_db_before_migration(
            &conn,
            root,
            from,
            config.backup_keep,
            Local::now(),
        )
        .map_err(|e| {
            Error::State(format!(
                "could not back up the database before upgrading it \
                 (schema {from}); nothing was changed: {e}"
            ))
        })?;
        crate::applog::info(format!("database schema upgrade from version {from}"));
    }
    db::migrate(&conn)?;
    Ok(conn)
}

/// SQLite's verdict on a file that is not (or no longer) a database.
fn is_unreadable_db(e: &Error) -> bool {
    matches!(
        e,
        Error::Db(rusqlite::Error::SqliteFailure(f, _))
            if matches!(
                f.code,
                rusqlite::ErrorCode::NotADatabase | rusqlite::ErrorCode::DatabaseCorrupt
            )
    )
}

/// Renames app.db and its WAL/SHM siblings to `app.db.unreadable-<ts>`
/// (+`-wal`/`-shm`) beside it. Not into backups/db: the restore list
/// would offer a database nobody can open.
fn set_aside_unreadable_db(root: &Path, now: chrono::DateTime<Local>) -> Result<PathBuf> {
    let db = db_path(root);
    let aside = db.with_extension(format!("db.unreadable-{}", now.format("%Y%m%d-%H%M%S")));
    fs::rename(&db, &aside).map_err(|e| Error::io_at(&db, e))?;
    for suffix in ["-wal", "-shm"] {
        let sibling = PathBuf::from(format!("{}{suffix}", db.display()));
        if sibling.exists() {
            let _ = fs::rename(&sibling, format!("{}{suffix}", aside.display()));
        }
    }
    Ok(aside)
}

/// Writes to a temp file in the same directory, then renames over the
/// target: a crash mid-write never truncates the file and the config
/// watcher never reads a half-written state. std::fs::rename replaces
/// an existing target on Windows too (MOVEFILE_REPLACE_EXISTING).
pub fn write_atomic(path: &Path, content: &str) -> Result<()> {
    write_atomic_bytes(path, content.as_bytes())
}

/// Name prefix/suffix of `write_atomic`'s staging files: `.<name>.<pid>-<seq>.tmp`.
/// The Notes tree hides them and sync never ships one - a crash can
/// leave one behind, and it is nobody's content.
pub fn is_staging_file(name: &str) -> bool {
    name.starts_with('.') && name.ends_with(".tmp")
}

/// `write_atomic` for raw bytes. The staging file is flushed to disk
/// before the rename, or a power cut right after it can leave the
/// target renamed into place but empty.
pub fn write_atomic_bytes(path: &Path, content: &[u8]) -> Result<()> {
    let dir = path
        .parent()
        .ok_or_else(|| Error::State(format!("no parent dir for {}", path.display())))?;
    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("file");
    // unique per write: the mirror is exported from commands and from the
    // watcher threads at once, and two writers sharing `.name.tmp` would
    // rename each other's half-written bytes into place
    static SEQ: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let seq = SEQ.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let tmp = dir.join(format!(".{name}.{}-{seq}.tmp", std::process::id()));
    let staged = (|| -> std::io::Result<()> {
        use std::io::Write;
        let mut file = fs::File::create(&tmp)?;
        file.write_all(content)?;
        file.sync_all()
    })();
    if let Err(e) = staged {
        let _ = fs::remove_file(&tmp);
        return Err(Error::io_at(path, e));
    }
    if let Err(e) = fs::rename(&tmp, path) {
        let _ = fs::remove_file(&tmp);
        return Err(Error::io_at(path, e));
    }
    Ok(())
}

/// The vault path is the only state kept outside the vault, in the OS
/// app-config dir, so the app can find the vault on startup.
pub fn read_vault_path(app_config_dir: &Path) -> Option<PathBuf> {
    let marker = app_config_dir.join("vault-path.txt");
    let raw = fs::read_to_string(marker).ok()?;
    let trimmed = raw.trim();
    if trimmed.is_empty() {
        None
    } else {
        Some(PathBuf::from(trimmed))
    }
}

pub fn write_vault_path(app_config_dir: &Path, vault: &Path) -> Result<()> {
    fs::create_dir_all(app_config_dir).at(app_config_dir)?;
    fs::write(
        app_config_dir.join("vault-path.txt"),
        vault.to_string_lossy().as_bytes(),
    )?;
    Ok(())
}

