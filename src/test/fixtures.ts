export type CommandHandlers = Record<string, (args?: unknown) => unknown>;

/** The baseline command set a mounted App needs; tests override per
 *  command. Unknown commands throw so a new invoke cannot pass silently. */
export function baseHandlers(overrides: CommandHandlers = {}): CommandHandlers {
  return {
    vault_status: () => "/test/vault",
    config_get: () => defaultConfig,
    config_default: () => defaultConfig,
    engine_run: () => emptyOutcome,
    lists_all: () => [],
    list_groups_all: () => [],
    tasks_snapshot: () => [],
    dashboard_context: () => emptyDashboard,
    calendar_outlook: () => [],
    habit_rates: () => [],
    // the phone's automatic pass runs on mount; with no handler its
    // rejection is swallowed by design and the test would only log it
    sync_now: () => emptySync,
    ...overrides,
  };
}
